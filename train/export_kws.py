"""Export the wake-word model to a .pte and write the device self-test headers.

Outputs:
  firmware/model/kws.pte
  firmware/src/features_test.h   the test clip (int16), its MFCC from features.py,
                                 and the per-coefficient normalisation
  firmware/src/kws_test_input.h  the normalised features and the PyTorch logits

Without --checkpoint the weights are seeded random (pipeline check: same ops,
same memory, same self-test mechanics). Train with train_kws.py and pass
--checkpoint train/out/kws.pt for the real thing.
"""

import argparse
import json
import pathlib

import numpy as np
import torch
from executorch.exir import to_edge_transform_and_lower

from features import FRAMES, N_COEF, SAMPLE_RATE, mfcc, test_audio
from kws_model import LABELS, KwsNet, example_input

REPO = pathlib.Path(__file__).resolve().parents[1]


def export_pte(model, out: pathlib.Path) -> None:
    model.eval()
    with torch.no_grad():
        ep = torch.export.export(model, example_input())
        edge = to_edge_transform_and_lower(ep)
        program = edge.to_executorch()
    ops = sorted({str(n.target) for n in program.exported_program().graph.nodes if n.op == "call_function"})
    print("operators in program:")
    for o in ops:
        print(f"  {o}")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_bytes(program.buffer)
    print(f"wrote {out} ({out.stat().st_size} bytes)")


def c_array(name, ctype, values, fmt, per_line):
    lines = [f"static const {ctype} {name}[{len(values)}] = {{"]
    for i in range(0, len(values), per_line):
        lines.append("\t" + ", ".join(fmt(v) for v in values[i:i + per_line]) + ",")
    lines.append("};")
    return lines


def write_headers(model, mean, std, out_dir: pathlib.Path) -> None:
    clip = test_audio()
    feats = mfcc(clip)
    normed = ((feats - mean) / std).astype(np.float32)
    with torch.no_grad():
        logits = model(torch.from_numpy(normed)[None, None])[0]

    h = [
        "/* Generated by train/export_kws.py; do not edit. */",
        "#pragma once",
        "#include <stdint.h>",
        f"#define FEAT_SAMPLE_RATE {SAMPLE_RATE}",
        f"#define FEAT_FRAMES {FRAMES}",
        f"#define FEAT_COEFFS {N_COEF}",
        f"#define FEAT_TEST_SAMPLES {len(clip)}",
    ]
    h += c_array("kTestAudio", "int16_t", clip.tolist(), lambda v: str(int(v)), 16)
    h += c_array("kTestMfcc", "float", feats.flatten().tolist(), lambda v: f"{v:.6f}f", N_COEF)
    h += c_array("kFeatMean", "float", mean.tolist(), lambda v: f"{v:.6f}f", N_COEF)
    h += c_array("kFeatStd", "float", std.tolist(), lambda v: f"{v:.6f}f", N_COEF)
    (out_dir / "features_test.h").write_text("\n".join(h) + "\n")

    k = [
        "/* Generated by train/export_kws.py; do not edit. */",
        "#pragma once",
        f"#define KWS_FRAMES {FRAMES}",
        f"#define KWS_COEFFS {N_COEF}",
        f"#define KWS_LABELS {len(LABELS)}",
        f"#define KWS_WAKE_INDEX {LABELS.index('hey_zephyr')}",
        "static const char *const kKwsLabels[KWS_LABELS] = {" + ", ".join(f'"{l}"' for l in LABELS) + "};",
    ]
    k += c_array("kTestInput", "float", normed.flatten().tolist(), lambda v: f"{v:.6f}f", N_COEF)
    k.append("static const float kTestLogits[KWS_LABELS] = {" + ", ".join(f"{v:.6f}f" for v in logits.tolist()) + "};")
    k.append(f"#define KWS_TEST_ARGMAX {int(logits.argmax())}")
    (out_dir / "kws_test_input.h").write_text("\n".join(k) + "\n")
    print(f"wrote features_test.h and kws_test_input.h: test clip argmax {int(logits.argmax())} ({LABELS[int(logits.argmax())]})")


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--checkpoint", type=pathlib.Path, help="train/out/kws.pt from train_kws.py")
    p.add_argument("--seed", type=int, default=0)
    p.add_argument("--pte", type=pathlib.Path, default=REPO / "firmware" / "model" / "kws.pte")
    p.add_argument("--src", type=pathlib.Path, default=REPO / "firmware" / "src")
    args = p.parse_args()

    torch.manual_seed(args.seed)
    ck = torch.load(args.checkpoint, map_location="cpu") if args.checkpoint else None
    model = KwsNet(ch=ck["ch"], blocks=ck["blocks"]) if ck and "ch" in ck else KwsNet()
    mean = np.zeros(N_COEF, dtype=np.float32)
    std = np.ones(N_COEF, dtype=np.float32)
    if ck:
        model.load_state_dict(ck["state_dict"])
        mean = np.asarray(ck["feat_mean"], dtype=np.float32)
        std = np.asarray(ck["feat_std"], dtype=np.float32)
        print(f"loaded {args.checkpoint}: {json.dumps(ck.get('metrics', {}))}")
    else:
        print("no --checkpoint: seeded random weights, identity normalisation (pipeline check only)")
    n = sum(p.numel() for p in model.parameters())
    print(f"KwsNet: {n} parameters ({n * 4 / 1024:.1f} KiB fp32)")
    export_pte(model, args.pte)
    write_headers(model, mean, std, args.src)


if __name__ == "__main__":
    main()
